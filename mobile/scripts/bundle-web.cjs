// The ESP webpage is the source of truth. Bundle it without a separate UI copy.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '../..');
const web = path.join(root, 'firmware/components/web_console');
let html = fs.readFileSync(path.join(web, 'index.html'), 'utf8');
for (const [name, mime] of [['logo.svg','image/svg+xml'],['hero.jpg','image/jpeg']]) {
  html = html.replaceAll('/assets/'+name, 'data:'+mime+';base64,'+fs.readFileSync(path.join(web,'assets',name)).toString('base64'));
}
const bridge = fs.readFileSync(path.join(__dirname, '../src/web-fetch.js'), 'utf8');
html = html.replace('<script>', '<script>'+bridge+'</script>\n<script>');
html = html.replace('<meta charset="utf-8">', `<meta charset="utf-8">
<meta http-equiv="Content-Security-Policy" content="default-src 'none'; script-src 'unsafe-inline'; style-src 'unsafe-inline'; img-src data:; connect-src 'none'; object-src 'none'; base-uri 'none'; form-action 'none'">`);
// BLE has a 10-second native result deadline; allow its outcome to arrive.
html = html.replace('timer=setTimeout(()=>abort.abort(),2000)', 'timer=setTimeout(()=>abort.abort(),15000)');
// Transport wording only; HTML layout, styles, behavior, and artwork stay shared.
html = html.replace('LOCAL WI-FI · NO INTERNET REQUIRED', 'BLUETOOTH · NO INTERNET REQUIRED');
const output = path.join(root,'mobile/src/generated/controller-page.ts');
const source = '// Generated by mobile/scripts/bundle-web.cjs. Do not edit.\nexport const controllerPage = '+JSON.stringify(html)+';\n';
if (process.argv.includes('--check')) {
  if (!fs.existsSync(output) || fs.readFileSync(output,'utf8')!==source) throw new Error('Run pnpm --filter @nordic/mobile bundle:web');
} else { fs.mkdirSync(path.dirname(output),{recursive:true}); fs.writeFileSync(output,source); }
