// Uses Node built-ins only. The ESP32 receives validated, compiled data.
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const root = path.resolve(__dirname, '..');
function validateCatalog(items) {
  if (!Array.isArray(items) || items.length > 32) throw Error('Maximum 32 workouts');
  const ids = new Set();
  const keys = (obj, expected) => {
    if (!obj || typeof obj !== 'object' || Array.isArray(obj) || Object.keys(obj).sort().join() !== expected.split(' ').sort().join()) throw Error('Missing or unknown fields');
  };
  const number = (v, min, max) => Number.isFinite(v) && v >= min && v <= max;
  for (const w of items) {
    keys(w, 'id name description default_duration_minutes default_intensity_percent segments');
    if (typeof w.id !== 'string' || !/^[a-z][a-z0-9-]{0,23}$/.test(w.id) || w.id === 'manual' || ids.has(w.id)) throw Error('Invalid or duplicate workout ID');
    ids.add(w.id);
    if (typeof w.name !== 'string' || !w.name.trim() || w.name.length > 60 || typeof w.description !== 'string' || w.description.length > 240) throw Error('Invalid name or description');
    if (!Number.isInteger(w.default_duration_minutes) || !number(w.default_duration_minutes,1,120) || !number(w.default_intensity_percent,50,150)) throw Error('Invalid defaults');
    if (!Array.isArray(w.segments) || w.segments.length < 1 || w.segments.length > 64) throw Error('Expected 1–64 segments');
    let total = 0;
    for (const s of w.segments) {
      keys(s, 'weight speed_mps grade_percent');
      if (!Number.isInteger(s.weight) || !number(s.weight,1,1000) || !number(s.speed_mps,0,5/1.5) || !number(s.grade_percent,0,10/1.5)) throw Error('Invalid segment or targets exceed software limits at 150% intensity');
      total += s.weight;
    }
    if (total > 10000) throw Error('Total segment weight exceeds 10000');
  }
  return items;
}
function generate(check = false) {
  const dir = path.join(root,'firmware/workouts');
  const files = fs.readdirSync(dir).filter(f=>f.endsWith('.json')).sort();
  if(files.some(f=>! /^[a-zA-Z0-9][a-zA-Z0-9_-]*\.json$/.test(f)))throw Error('Workout filenames must use letters, digits, hyphens, or underscores');
  const catalog = validateCatalog(files.map(f=>JSON.parse(fs.readFileSync(path.join(dir,f),'utf8'))));
  const quote = v=>JSON.stringify(v).replace(/\\u([0-9a-f]{4})/gi,(_,hex)=>String.fromCharCode(parseInt(hex,16)));
  // Encode JSON as UTF-8 byte escapes so arbitrary text cannot become C syntax.
  const cString = v=>'"'+[...Buffer.from(v)].map(b=>'\\'+b.toString(8).padStart(3,'0')).join('')+'"';
  let out = '// Generated by tools/generate-workouts.cjs; edit firmware/workouts/*.json.\n';
  catalog.forEach((w,i)=>{
    out += `static const workout_segment_t segments_${i}[] = {\n`;
    out += w.segments.map(s=>`    {${s.weight}, ${s.speed_mps.toFixed(8)}f, ${s.grade_percent.toFixed(8)}f},`).join('\n')+'\n};\n';
  });
  out += 'static const workout_definition_t workouts[] = {\n';
  catalog.forEach((w,i)=>{out+=`    {${quote(w.id)}, ${w.segments.length}, ${w.segments.reduce((a,s)=>a+s.weight,0)}, segments_${i}},\n`;});
  out += '    {NULL, 0, 0, NULL}\n};\n';
  out += `static const char workout_catalog_json[] = ${cString(JSON.stringify(catalog))};\n`;
  const generated = path.join(root,'firmware/components/test_session');
  const manifest = '# Generated; verify source files before building.\n'+
    'set(source_dir "${CMAKE_CURRENT_LIST_DIR}/../../workouts")\nfile(GLOB actual RELATIVE "${source_dir}" "${source_dir}/*.json")\nlist(SORT actual)\n'+
    `set(expected "${files.join(';')}")\n`+
    'if(NOT "${actual}" STREQUAL "${expected}")\n message(FATAL_ERROR "Workout files changed. Run node tools/generate-workouts.cjs")\nendif()\n'+
    files.map(f=>`file(SHA256 "\${source_dir}/${f}" hash)\nif(NOT hash STREQUAL "${crypto.createHash('sha256').update(fs.readFileSync(path.join(dir,f))).digest('hex')}")\n message(FATAL_ERROR "Workout ${f} changed. Run node tools/generate-workouts.cjs")\nendif()\n`).join('');
  for (const [name,content] of [['workouts.generated.h',out],['workouts.check.cmake',manifest]]) {
    const dest=path.join(generated,name);
    if(check){if(!fs.existsSync(dest)||fs.readFileSync(dest,'utf8')!==content)throw Error('Stale generated workouts. Run node tools/generate-workouts.cjs');}
    else fs.writeFileSync(dest,content);
  }
  return catalog;
}
module.exports={validateCatalog,generate};
if(require.main===module){try{console.log(`${generate(process.argv.includes('--check')).length} workouts validated${process.argv.includes('--check')?'':' and generated'}.`);}catch(e){console.error(e.message);process.exitCode=1;}}
