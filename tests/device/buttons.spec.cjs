const {test,expect,status}=require('./fixtures.cjs');
test('physical relay capability retains original numeric controls and workouts',async({operator:page,request})=>{
  test.skip(process.env.NORDIC_BUTTON_PREVIEW!=='1','Run against local preview advertising physical button capability.');
  await expect(page.locator('#speed')).toBeEnabled();
  await expect(page.locator('#grade')).toBeEnabled();
  await expect(page.locator('#workoutSection')).toBeVisible();
  await expect(page.getByRole('button',{name:'Rolling Hills',exact:true})).toBeEnabled();
  await expect(page.locator('#stopAll')).toHaveCount(0);
  await expect(page.locator('#release')).toHaveCount(0);
  await page.locator('#runToggle').click();
  await page.locator('#speed').fill('3.6');
  await expect.poll(async()=> (await status(request)).requested_speed_mps).toBe(1);
  await page.locator('#grade').fill('2');
  await expect.poll(async()=> (await status(request)).requested_grade_percent).toBe(2);
  await page.locator('#speedUp').click();
  await expect(page.locator('#acceptedSpeed')).toHaveText('4.1');
  await page.locator('#gradeDown').click();
  await expect(page.locator('#acceptedGrade')).toHaveText('1.5');
  await page.locator('#speedSlider').fill('7.5');
  await expect.poll(async()=> (await status(request)).requested_speed_mps).toBeCloseTo(7.5/3.6,3);
  await page.locator('#mph').click();
  await expect(page.locator('#acceptedSpeed')).toHaveText('4.7');
  await page.locator('#runToggle').click();
  await expect(page.locator('#mode')).toHaveText('idle');
  await page.waitForTimeout(650);
  await page.getByRole('button',{name:'Rolling Hills',exact:true}).click();
  await page.locator('#duration').fill('1');
  await page.locator('#intensity').fill('100');
  await page.locator('#runToggle').click();
  await expect(page.locator('#mode')).toHaveText('running');
  await expect.poll(async()=> (await status(request)).workout.active).toBe(true);
  await page.locator('#grade').fill('4');
  await expect.poll(async()=> (await status(request)).workout.overridden).toBe(true);
  await page.locator('#runToggle').click();
  await expect(page.locator('#mode')).toHaveText('idle');
  await page.setViewportSize({width:390,height:844});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
  await page.screenshot({path:'.local/restored-functional-page.png',fullPage:true});
});
